def least_prime_1mod(d):
    p = d + 1
    while True:
        if all(p % q for q in range(2, int(p ** 0.5) + 1)):
            if (p - 1) % d == 0:
                return p
        p += d

def rank_modp(rows, p):
    M = [r[:] for r in rows]
    rank, col = 0, 0
    ncols = len(M[0]) if M else 0
    for col in range(ncols):
        piv = next((r for r in range(rank, len(M)) if M[r][col]), None)
        if piv is None:
            continue
        M[rank], M[piv] = M[piv], M[rank]
        inv = pow(M[rank][col], p - 2, p)
        M[rank] = [x * inv % p for x in M[rank]]
        for r in range(len(M)):
            if r != rank and M[r][col]:
                c = M[r][col]
                M[r] = [(x - c * y) % p for x, y in zip(M[r], M[rank])]
        rank += 1
    return rank

from itertools import combinations

for d in [3, 5, 7, 9, 11, 13, 15, 21, 25, 27, 33, 35]:
    q = spf(d)
    p = least_prime_1mod(d)
    g = primitive_root(p)
    h = pow(g, (p - 1) // d, p)
    prim = [pow(h, u, p) for u in units_mod(d)]
    found = False
    for w in range(2, q):
        for rest in combinations(range(1, d), w - 1):
            support = (0,) + rest
            rows = [[pow(th, e, p) for e in support] for th in prim]
            if rank_modp(rows, p) < w:
                found = True
                break
        if found:
            break
    # q-gon: weight-q multiple of Phi_d
    qgon = [0] * d
    for s in range(q):
        qgon[s * (d // q)] = 1
    rem = poly_rem_modp(qgon, cyclotomic(d), p)
    check(not found and rem == [0],
          f"d={d} (p={p}): no codeword below weight {q}, q-gon hits it "
          f"-- tau({d}) = {q}")

