    fs.append([(1, 1, 1), (-g % p, 0, 0)])                     # xy = g
    for _ in range(25):
        terms = random.randint(3, 6)
        fs.append([(random.randint(1, p - 1), random.randint(0, 4),
                    random.randint(0, 4)) for _ in range(terms)])
    return fs

