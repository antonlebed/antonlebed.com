# ---------------------------------------------------------------- helpers

def factorize(n):
    fs, q = {}, 2
    while q * q <= n:
        while n % q == 0:
            fs[q] = fs.get(q, 0) + 1
            n //= q
        q += 1
    if n > 1:
        fs[n] = fs.get(n, 0) + 1
    return fs

def spf(n):
    q = 2
    while q * q <= n:
        if n % q == 0:
            return q
        q += 1
    return n

def mult_order(x, p):
    n, o = p - 1, 1
    t = x % p
    assert t != 0
    while t != 1:
        t = t * x % p
        o += 1
    return o

def primitive_root(p):
    n = p - 1
    qs = list(factorize(n))
    for g in range(2, p):
        if all(pow(g, n // q, p) != 1 for q in qs):
            return g

def units_mod(n):
    return [u for u in range(n) if gcd(u, n) == 1]

_CYC = {}
def cyclotomic(d):
    """Integer coefficient list of Phi_d, low degree first."""
    if d in _CYC:
        return _CYC[d]
    # (T^d - 1) / prod_{e | d, e < d} Phi_e, exact integer division
    num = [-1] + [0] * (d - 1) + [1]
    for e in range(1, d):
        if d % e == 0:
            den = cyclotomic(e)
            num = poly_div_exact(num, den)
    _CYC[d] = num
    return num

def poly_div_exact(A, B):
    A = A[:]
    out = [0] * (len(A) - len(B) + 1)
    for i in range(len(A) - len(B), -1, -1):
        c = A[i + len(B) - 1] // B[-1]
        out[i] = c
        for j, bj in enumerate(B):
            A[i + j] -= c * bj
    assert all(x == 0 for x in A[:len(B) - 1])
    return out

def poly_rem_modp(A, B, p):
    """Remainder of A mod B over F_p (lists, low degree first)."""
    A = [a % p for a in A]
    B = [b % p for b in B]
    while len(B) > 1 and B[-1] == 0:
        B.pop()
    inv = pow(B[-1], p - 2, p)
    for i in range(len(A) - len(B), -1, -1):
        c = A[i + len(B) - 1] * inv % p
        if c:
            for j, bj in enumerate(B):
                A[i + j] = (A[i + j] - c * bj) % p
    while len(A) > 1 and A[-1] == 0:
        A.pop()
    return A

# A curve is a list of (coeff, i, j): f(x, y) = sum c x^i y^j.

def eval_curve(f, x, y, p):
    return sum(c * pow(x, i, p) * pow(y, j, p) for c, i, j in f) % p

def brute_stable(f, a, b, p):
    """Definition: the whole orbit (a^u, b^u), u unit mod p-1, in the shadow."""
    return all(eval_curve(f, pow(a, u, p), pow(b, u, p), p) == 0
               for u in units_mod(p - 1))

def fiber(f, a, b, p):
    """d, collected fiber as exponent list F (F[E] = coeff of T^E)."""
    d = (lambda oa, ob: oa * ob // gcd(oa, ob))(mult_order(a, p),
                                                mult_order(b, p))
    g = primitive_root(p)
    h = pow(g, (p - 1) // d, p)          # generator of mu_d
    dlog = {}
    t = 1
    for e in range(d):
        dlog.setdefault(t, e)
        t = t * h % p
    F = [0] * d
    for c, i, j in f:
        w = pow(a, i, p) * pow(b, j, p) % p
        F[dlog[w]] = (F[dlog[w]] + c) % p
    return d, F

def criterion(f, a, b, p):
    """Returns (stable?, species): species in {'group','antipodal','codeword'}."""
    d, F = fiber(f, a, b, p)
    if all(c == 0 for c in F):
        return True, 'group'
    rem = poly_rem_modp(F, [c % p for c in cyclotomic(d)], p)
    if rem != [0]:
        return False, None
    wt = sum(1 for c in F if c)
    if wt == 2 and d % 2 == 0:
        es = [e for e, c in enumerate(F) if c]
        if (es[1] - es[0]) % d == d // 2 and F[es[0]] == F[es[1]]:
            return True, 'antipodal'
    return True, 'codeword'

