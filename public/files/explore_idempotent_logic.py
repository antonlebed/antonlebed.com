# Mechanical: random connective trees.
def rand_formula(depth):
    if depth == 0:
        return random.randrange(3)
    op = random.choice(("AND", "OR", "IMP", "NOT"))
    if op == "NOT":
        return ("NOT", rand_formula(depth - 1))
    return (op, rand_formula(depth - 1), rand_formula(depth - 1))

def eval_formula(f, env, n):
    if isinstance(f, int):
        return env[f]
    if f[0] == "NOT":
        return NOT(eval_formula(f[1], env, n), n)
    x = eval_formula(f[1], env, n)
    y = eval_formula(f[2], env, n)
    return {"AND": AND, "OR": OR, "IMP": IMP}[f[0]](x, y, n)

strict = 0
