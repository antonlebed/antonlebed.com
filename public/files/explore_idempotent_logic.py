def NOT(a, n=N):    return (1 - a) % n
def IMP(a, b, n=N): return (1 - a + a * b) % n
def DELTA(a, n=N):  return (a * a - a) % n

def supp(a, ring):
    return frozenset(i for i, r in enumerate(encode(a, ring)) if r != 0)

