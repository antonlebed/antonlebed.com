def iroot_floor(a, k):
    """largest r >= 0 with r^k <= a (exact, integers)."""
    if a < 2:
        return a
    r = int(round(a ** (1.0 / k)))
    while r ** k > a:
        r -= 1
    while (r + 1) ** k <= a:
        r += 1
    return r

def make_supply(c):
    """c = p/q. m(g) = ceil g^(q/p) = least m with m^p >= g^q;
    M(d) = floor d^(p/q) = largest M with M^q <= d^p."""
    p, q = c.numerator, c.denominator
    def m(g):
        if g <= 0:
            return 0
        r = iroot_floor(g ** q, p)
        return r if r ** p >= g ** q else r + 1
    def M(d):
        return iroot_floor(d ** p, q)
    return m, M

def landings_pointer(m, n_land):
    """Landing passes t_1..t_n by the closed pointer: from a landing at
    t the gap is d = min{j >= 2 : j >= m(t + j + 2)}, non-decreasing."""
    t, d = 0, 2
    out = []
    while len(out) < n_land:
        # least j >= d with j >= m(t + j + 2): iterate d <- m(t + d + 2),
        # every j below the image failing since m is non-decreasing
        while True:
            nd = m(t + d + 2)
            if nd <= d:
                break
            d = nd
        t += d
        out.append((t, d))
    return out

def landings_rider(m, t_max):
    """The tick rider itself: v := (v + 1) mod max(2, m(g)), g = t + 2,
    one pass per tick; a landing is a pass at which v returns to 0."""
    v = 0
    out = []
    for t in range(1, t_max + 1):
        v = (v + 1) % max(2, m(t + 2))
        if v == 0:
            out.append(t)
    return out

def star_discrepancy(xs):
    xs = sorted(xs)
    n = len(xs)
    best = 0.0
    for i, x in enumerate(xs, 1):
        best = max(best, i / n - x, x - (i - 1) / n)
    return best

def lag_histogram(xs, lag=1, bins=100):
    h = [0] * bins
    for i in range(len(xs) - lag):
        dlt = (xs[i + lag] - xs[i]) % 1.0
        h[min(bins - 1, int(dlt * bins))] += 1
    tot = sum(h)
    return max(h) / tot

def word_report(name, xs):
    d3 = star_discrepancy(xs[:1000])
    d4 = star_discrepancy(xs[:10000])
    d5 = star_discrepancy(xs[:100000])
    slope = math.log(d5 / d4) / math.log(10)
    top1 = lag_histogram(xs, 1)
    top2 = lag_histogram(xs, 2)
    print("  %-22s D*(10^3)=%.4f D*(10^4)=%.4f D*(10^5)=%.5f "
          "slope %.2f | lag-1 top bin %.3f, lag-2 %.3f"
          % (name, d3, d4, d5, slope, top1, top2))
    if len(xs) >= 1000000:
        d6 = star_discrepancy(xs[:1000000])
        slope6 = math.log(d6 / d5) / math.log(10)
        lags = " ".join("%.3f" % lag_histogram(xs[:200000], k)
                        for k in range(1, 9))
        print("  %-22s D*(10^6)=%.6f slope over the last decade %.2f | "
              "lag 1..8 heaviest bins %s" % ("", d6, slope6, lags))
        return slope6, top1
    return slope, top1

