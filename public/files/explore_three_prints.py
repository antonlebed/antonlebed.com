def pmul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        b >>= 1
    return r

def pmod(a, b):
    db = b.bit_length() - 1
    while a and a.bit_length() - 1 >= db:
        a ^= b << (a.bit_length() - 1 - db)
    return a

def pgcd(a, b):
    while b:
        a, b = b, pmod(a, b)
    return a

def pdeg(a):
    return a.bit_length() - 1

def x_pow2n_plus_x(n):
    """x^(2^n) + x as an integer polynomial over F_2 (degree 2^n)."""
    return (1 << (1 << n)) ^ 2

def rabin_irreducible(m, n):
    """Rabin: deg m = n, m | x^(2^n) + x, and gcd(m, x^(2^(n/q)) + x) = 1
    for every prime q | n -- computed with the full wall polynomials,
    which is affordable at n = 6."""
    if pdeg(m) != n:
        return False
    if pmod(x_pow2n_plus_x(n), m) != 0:
        return False
    for q in (2, 3, 5, 7):
        if n % q == 0:
            if pgcd(m, x_pow2n_plus_x(n // q)) != 1:
                return False
    return True

def q2():
    print("\nQ2  THE SPLITTING-FIELD WALK at clock 63 from seed x")
    n = 6
    wall = x_pow2n_plus_x(n)
    N = 0b10  # x
    moves = []
    while True:
        found = None
        for e in range(1, n + 1):
            cands = [m for m in range(1 << e, 1 << (e + 1))
                     if pmod(wall, m) == 0 and pgcd(m, N) == 1]
            if cands:
                found = (e, min(cands), len(cands))
                break
        if found is None:
            break
        e, m, k = found
        N = pmul(N, m)
        moves.append((e, m, k))
        print("  move %2d: degree %d, m = %s (%d admissible at that "
              "degree), state degree %d"
              % (len(moves), e, format(m, "b"), k, pdeg(N)))
    print("  walk dead after %d moves; final state == x^64 + x: %s"
          % (len(moves), N == wall))
    # the derivation's check: from the state holding every irreducible
    # of degree 1, 2, 3, admissibility of a sextic == Rabin's test
    S = 0b10
    for e in (1, 2, 3):
        for m in range(1 << e, 1 << (e + 1)):
            if pmod(wall, m) == 0 and pgcd(m, S) == 1:
                S = pmul(S, m)
    agree = 0
    adm = 0
    for m in range(1 << 6, 1 << 7):
        a = (pmod(wall, m) == 0 and pgcd(m, S) == 1)
        r = rabin_irreducible(m, 6)
        agree += (a == r)
        adm += a
    print("  from the degree-1..3 state, sextic admissibility agrees "
          "with Rabin's test at %d of 64 (%d admissible)" % (agree, adm))
    return moves, N == wall, agree, adm

