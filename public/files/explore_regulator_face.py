import math

# ---------------------------------------------------------------- basics


def vp(n, p):
    """p-adic valuation of a nonzero integer."""
    assert n != 0
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v


def factor(n):
    """Trial-division factorization of |n| >= 1 into {p: e}."""
    n = abs(n)
    assert n >= 1
    out = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            out[d] = out.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        out[n] = out.get(n, 0) + 1
    return out


# ----------------------------------------------- real quadratic K layer

HENSEL_K = 40   # lift precision p^HENSEL_K
BOUND = 60      # coefficient bound for enumeration


class Field:
    """K = Q(sqrt(D)), D squarefree positive (real quadratic)."""

    def __init__(self, D, ram, pool):
        self.D = D
        self.ram = ram            # the ramified primes we may use
        self.pool = pool          # rational primes places are built over
        self.places = []
        for p in pool:
            self.places.extend(self.places_over(p))
        self.sqrtD = math.sqrt(D)

    def norm(self, a, b):
        """N(a + b sqrt(D)) = a^2 - D b^2 (can be negative)."""
        return a * a - self.D * b * b

    def splitting(self, p):
        if p in self.ram:
            return "ram", []
        roots = [r for r in range(p) if (r * r - self.D) % p == 0]
        return ("split", roots) if roots else ("inert", [])

    def places_over(self, p):
        kind, roots = self.splitting(p)
        if kind == "split":
            return [Place(self, p, "split", r) for r in sorted(roots)]
        return [Place(self, p, kind)]

    def logs_arch(self, a, b):
        """(log|sigma1(x)|, log|sigma2(x)|), sigma1: sqrt(D) -> +."""
        s = b * self.sqrtD
        return math.log(abs(a + s)), math.log(abs(a - s))


class Place:
    """A finite place over p: kind in ram/split/inert; split places
    carry the root r and its Hensel lift. NP = p^f."""

    def __init__(self, K, p, kind, r=None):
        self.K, self.p, self.kind, self.r = K, p, kind, r
        self.f = 2 if kind == "inert" else 1
        self.NP = p ** self.f
        if kind == "split":
            self.R, self.Rmod = self.hensel(p, r)

    def hensel(self, p, r):
        D = self.K.D
        mod, R = p, r
        for _ in range(HENSEL_K - 1):
            newmod = mod * p
            t = (((D - R * R) // mod) * pow(2 * R, -1, p)) % p
            R = (R + t * mod) % newmod
            mod = newmod
        assert (R * R - D) % mod == 0
        return R, mod

    def name(self):
        tag = {"ram": "ram", "inert": "inert",
               "split": "r=%d" % self.r if self.r is not None else ""}[
                   self.kind]
        return "P(%d,%s)" % (self.p, tag)

    def val(self, a, b):
        """v_P(a + b sqrt(D)) for a nonzero element."""
        n = self.K.norm(a, b)
        if self.kind == "ram":
            return vp(n, self.p)                 # e = 2, f = 1
        if self.kind == "inert":
            v = vp(n, self.p) if n % self.p == 0 else 0
            assert v % 2 == 0, "inert valuation of a norm must be even"
            return v // 2
        x = (a + b * self.R) % self.Rmod
        if x == 0:
            raise AssertionError("Hensel precision exceeded")
        v = vp(x, self.p)
        assert v < HENSEL_K - 5, "valuation too close to lift precision"
        return v


# ------------------------------------------------- integer lattice layer

def echelon_tracked(vectors, k):
    """Integer echelon basis of the lattice spanned by vectors in Z^k,
    each row carrying its combination {source_index: exponent} so the
    basis rows remain exact integer combinations of the sources. Row
    ops: subtract integer multiples, negate, drop zeros -- lattice
    preserved. Returns (basis_rows, combos)."""
    rows = []
    for i, v in enumerate(vectors):
        if any(v):
            rows.append((list(v), {i: 1}))

    def sub(row, q, small):
        rv, rc = row
        sv, sc = small
        for j in range(k):
            rv[j] -= q * sv[j]
        for key, e in sc.items():
            rc[key] = rc.get(key, 0) - q * e
            if rc[key] == 0:
                del rc[key]

    basis = []
    for col in range(k):
        while True:
            nz = [r for r in rows if r[0][col] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda r: abs(r[0][col]))
            small = nz[0]
            for r in nz[1:]:
                q = r[0][col] // small[0][col]
                sub(r, q, small)
            rows = [r for r in rows if any(r[0])]
        nz = [r for r in rows if r[0][col] != 0]
        if nz:
            piv = nz[0]
            if piv[0][col] < 0:
                piv = ([-x for x in piv[0]],
                       {key: -e for key, e in piv[1].items()})
            basis.append(piv)
            rows = [r for r in rows if r is not nz[0]]
    return [b[0] for b in basis], [b[1] for b in basis]


def lattice_index(basis, k):
    """Index of the lattice in Z^k from an echelon basis (product of
    pivots), or None if the rank is short."""
    if len(basis) != k:
        return None
    idx = 1
    for row in basis:
        piv = next(x for x in row if x != 0)
        idx *= abs(piv)
    return idx


def det_abs(M):
    """|det| of a square float matrix by Gaussian elimination."""
    n = len(M)
    A = [row[:] for row in M]
    d = 1.0
    for i in range(n):
        piv = max(range(i, n), key=lambda r: abs(A[r][i]))
        if abs(A[piv][i]) < 1e-12:
            return 0.0
        if piv != i:
            A[i], A[piv] = A[piv], A[i]
        d *= A[i][i]
        for r in range(i + 1, n):
            f = A[r][i] / A[i][i]
            for c in range(i, n):
                A[r][c] -= f * A[i][c]
    return abs(d)


# ------------------------------------------------------- S-unit engine

def enumerate_s_units(K, s_places):
    """All a + b sqrt(D), |a|,|b| <= BOUND, that are S-units for
    S = {both archimedean} u s_places: norm support inside the S
    rational primes, valuation 0 at every pool place over a support
    prime that is not in S. Returns list of (a, b, valvec) with
    valvec over s_places. Excludes 0; keeps torsion (norm +-1)."""
    s_primes = {P.p for P in s_places}
    out = []
    for a in range(-BOUND, BOUND + 1):
        for b in range(-BOUND, BOUND + 1):
            if a == 0 and b == 0:
                continue
            n = K.norm(a, b)
            supp = factor(n) if abs(n) != 1 else {}
            if any(p not in s_primes for p in supp):
                continue
            ok = True
            for P in K.places:
                if P.p in supp and P not in s_places:
                    if P.val(a, b) != 0:
                        ok = False
                        break
            if not ok:
                continue
            out.append((a, b, tuple(P.val(a, b) for P in s_places)))
    return out


def fundamental_unit(K, units):
    """Minimal positive log among enumerated units; (a, b, log)."""
    best = None
    for (a, b, _) in units:
        if a < 0 or (a == 0 and b < 0):
            a, b = -a, -b            # torsion is {+-1}: fix the sign
        l1, _l2 = K.logs_arch(a, b)
        if l1 > 1e-9 and (best is None or l1 < best[2]):
            best = (a, b, l1)
    assert best is not None, "no nontrivial unit enumerated"
    return best


def measure(K, s_places, label):
    """Measure (rank, index, R_S, ratio) at S = arch u s_places."""
    k = len(s_places)
    elems = enumerate_s_units(K, s_places)
    units = [(a, b, v) for (a, b, v) in elems if not any(v)]
    eps = fundamental_unit(K, units)

    # norm identity control (exact): |N| = prod NP^v over s_places
    for (a, b, v) in elems:
        n = abs(K.norm(a, b))
        pr = 1
        for P, e in zip(s_places, v):
            pr *= P.NP ** e
        assert n == pr, "norm identity fails at %s" % ((a, b),)

    basis, combos = echelon_tracked([v for (_, _, v) in elems], k)
    rank = len(basis)
    idx = lattice_index(basis, k)

    # fundamental system log vectors (drop sigma2): eps + basis rows
    def logvec(a, b):
        l1, _ = K.logs_arch(a, b)
        return [l1] + [-P.val(a, b) * math.log(P.NP) for P in s_places]

    rows = [[eps[2]] + [0.0] * k]
    maxsum = 0.0
    for comb in combos:
        vec = [0.0] * (k + 1)
        full = [0.0] * (k + 2)
        for i, e in comb.items():
            a, b, _ = elems[i]
            lv = logvec(a, b)
            l1, l2 = K.logs_arch(a, b)
            for j in range(k + 1):
                vec[j] += e * lv[j]
            full[0] += e * l1
            full[1] += e * l2
            for j in range(k):
                full[2 + j] += e * lv[1 + j]
        maxsum = max(maxsum, abs(sum(full)))
        rows.append(vec)
    R_S = det_abs(rows) if rank == k else None
    ratio = None
    if R_S is not None:
        prod = 1.0
        for P in s_places:
            prod *= math.log(P.NP)
        ratio = R_S / (eps[2] * prod)
    print("  %-22s rank %d  index %s  R_S %s  ratio %s  logsum %.1e"
          % (label, rank + 1 if rank == k else rank,
             idx, "%.6f" % R_S if R_S is not None else "short",
             "%.6f" % ratio if ratio is not None else "-", maxsum))
    return rank, idx, R_S, ratio, eps


