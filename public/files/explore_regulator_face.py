    assert all(c not in sq5 for c in bad)
    print("  mod-5 obstruction: {+-2,+-3} mod 5 =", sorted(set(bad)),
          "squares mod 5 =", sorted(sq5), "-- disjoint")

    print("== K1 = Q(sqrt2), Cl trivial ==")
    P2, P3 = pl(K1, 2, "ram"), pl(K1, 3, "inert")
    P7a, P7b = pl(K1, 7, "split", 3), pl(K1, 7, "split", 4)
    P17a, P17b = pl(K1, 17, "split", 6), pl(K1, 17, "split", 11)
    k1_sets = [
        ("{}", []),
        ("{P2}", [P2]),
        ("{P3 inert}", [P3]),
        ("{both P7}", [P7a, P7b]),
        ("{P7 r=3}", [P7a]),
        ("{P2,P3}", [P2, P3]),
        ("{P2,both P7}", [P2, P7a, P7b]),
        ("{P2,P3,P7x2,P17x2}", [P2, P3, P7a, P7b, P17a, P17b]),
    ]
    eps1 = None
    for label, s in k1_sets:
        _, _, _, _, eps1 = measure(K1, s, label)
    print("  fundamental unit K1: (%d,%d)  R_K = %.6f  (hand: (1,1),"
          " log(1+sqrt2) = %.6f)"
          % (eps1[0], eps1[1], eps1[2], math.log(1 + math.sqrt(2))))

    print("== F3 factor-identity discriminator ==")
    _, _, R_S, _, eps = measure(K1, [P3], "{P3 inert} again")
    disc = R_S / (eps[2] * math.log(3))
    print("  R_S / (R_K * log 3) = %.6f  (per-term law: 2.0;"
          " rational-prime reading: 1.0)" % disc)

    print("== K2 = Q(sqrt10), Cl = Z/2 ==")
    Q2 = pl(K2, 2, "ram")
    Q3a, Q3b = pl(K2, 3, "split", 1), pl(K2, 3, "split", 2)
    Q41a, Q41b = pl(K2, 41, "split", 16), pl(K2, 41, "split", 25)
    k2_sets = [
        ("{}", []),
        ("{P2}", [Q2]),
        ("{both P3}", [Q3a, Q3b]),
        ("{P3 r=2}", [Q3b]),
        ("{both P41}", [Q41a, Q41b]),
        ("{P41 r=16}", [Q41a]),
        ("{P2,both P3}", [Q2, Q3a, Q3b]),
        ("{P2,both P41}", [Q2, Q41a, Q41b]),
    ]
    eps2 = None
    for label, s in k2_sets:
        _, _, _, _, eps2 = measure(K2, s, label)
    print("  fundamental unit K2: (%d,%d)  R_K = %.6f  (hand: (3,1),"
          " log(3+sqrt10) = %.6f)"
          % (eps2[0], eps2[1], eps2[2], math.log(3 + math.sqrt(10))))

    assert (eps1[0], eps1[1]) == (1, 1)
    assert (eps2[0], eps2[1]) == (3, 1)
    print("ALL GREEN")


