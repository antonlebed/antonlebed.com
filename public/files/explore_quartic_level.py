    print()
    print("  %-12s %-16s %-16s %-16s" % ("", "dE = E1-E2", "dN = N1-N2",
                                        "dC = dE-dN"))
    shift = {}
    for key in keys:
        if not all(key in t for t in (emp[1], nul[1], emp[2], nul[2])):
            continue
        dE = diff(emp[1][key], emp[2][key])
        dN = diff(nul[1][key], nul[2][key])
        dC = diff(dE, dN)
        shift[key] = (dE, dN, dC)
        lab = ("rank %d" % key) if isinstance(key, int) else (
            "ranks %d-%d" % key)
        print("  %-12s %s  %s  %s  z(dC) %+.1f"
              % (lab, fmt(*dE), fmt(*dN), fmt(*dC), z_of(dC)))

    section("THE NULL'S SHAPE: RANK 1 BY |d| BAND, AND BY SUB-BOUND COUNT")
    print("  %-16s %-22s %-22s" % ("|d| band", "empirical rank-1 share",
                                  "null rank-1 share"))
    erows = {i: QS.field_rows(pops[i]) for i in (1, 2)}
    for (lo, hi) in BANDS:
        i = 1 if hi <= 24000 else 2
        e = band_rank1(erows[i], lo, hi)
        n = band_rank1(nrows[i], lo, hi)
        if e is None or n is None:
            continue
        print("  %6d-%-6d    %s (%4d)     %s (%4d)"
              % (lo, hi, fmt(e[0], e[1]), e[2], fmt(n[0], n[1]), n[2]))
    print()
    print("  C4: the null's rank-1 excess by sub-bound partial count k, over"
          " fields whose sub-bound split set holds no non-square, against"
          " (1/2)/(1 - 2^-k) - 1/2 (both populations pooled):")
    allrows = nrows[1] + nrows[2]
    c4_ok = True
    for k in K_CELLS:
        vals = [row['ns'][0] for row in allrows
                if row['k'] == k and not row['split_ns']]
        pred = 0.5 / (1.0 - 2.0 ** (-k)) - 0.5
        if len(vals) < 2:
            print("    k = %d: no fields" % k)
            continue
        mu, se = mean_se(vals)
        flag = "" if len(vals) < MIN_CELL else (
            "  within 2 sigma" if abs(mu - pred) < 2 * se else "  OFF")
        if len(vals) >= MIN_CELL and abs(mu - pred) >= 2 * se:
            c4_ok = False
        print("    k = %d: null %s  algebra %+.3f  (%d fields)%s"
              % (k, fmt(mu, se), pred, len(vals), flag))
    vals = [row['ns'][0] for row in allrows if row['split_ns']]
    if len(vals) >= 2:
        print("    fields whose split set holds a non-square: null %s"
              " (%d fields), the algebra's zero" % (fmt(*mean_se(vals)),
                                                   len(vals)))
    ok(c4_ok, "C4: a sub-bound cell of at least %d fields is off the"
       " algebra" % MIN_CELL)
    print("  C4 PASSES: the null's cells sit on the algebra")

    section("THE VERDICT (P1 / P2, frozen)")
    if STRIDE > 1:
        print("  rehearsal: the verdict is read on the full populations only"
              " (dE is the siblings' shift)")
        print("\n%d checks passed, %.1f s" % (CHECKS, time.time() - t0))
        return
    dE1, dN1, dC1 = shift[1]
    dC13 = shift[(1, 3)][2]
    half = 0.5 * dE1[0]
    print("  rank 1: dE %s, dN %s, half of dE %+.3f, dN + 2 sigma %+.3f;"
          " dC %s (z %+.1f), ranks 1-3 dC %s (z %+.1f)"
          % (fmt(*dE1), fmt(*dN1), half, dN1[0] + 2 * dN1[1], fmt(*dC1),
             z_of(dC1), fmt(*dC13), z_of(dC13)))
    p1 = dN1[0] >= half and abs(z_of(dC1)) < 2 and abs(z_of(dC13)) < 2
    p2 = (dN1[0] + 2 * dN1[1] < half) and abs(z_of(dC1)) >= 2
    if p1:
        print("  P1: THE CONFOUND NAMED -- the null moves by the shift and"
              " the corrected shift is zero")
    elif p2:
        print("  P2: |d| STANDS -- the null moves by under half the shift"
              " at 2 sigma and the corrected shift survives")
    else:
        print("  MIXED -- neither letter met; the null moves by a fraction"
              " of the shift")

    print("\n%d checks passed, %.1f s" % (CHECKS, time.time() - t0))


