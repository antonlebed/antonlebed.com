# ---------------------------------------------------------------- the null
def split_nonsquare_below(rec):
    """Does a sub-bound split place already carry a non-square?"""
    G = rec['G']
    M = EE.minkowski(rec['d'])
    for p, t in rec['types'].items():
        if p > M or t == 'dropped' or t[0] != 'split':
            continue
        if any(key not in G.squares for key in t[1]):
            return True
    return False


def subbound_partial_count(rec):
    """The partial places the condition actually reads: below M, classed
    (a dropped place carries no class and is outside the condition), and
    among the drawn places."""
    M = EE.minkowski(rec['d'])
    drawn = set(p for (p, key) in rec['places'])
    return sum(1 for p, t in rec['types'].items()
               if p <= M and t != 'dropped' and t[0] == 'partial'
               and p in drawn)


def null_rows(recs, rng, mode):
    """One row per field: the non-square indicator minus 1/2 by rank,
    averaged over the field's accepted draws. mode: 'free' (no
    rejection), 'subbound' (C5's condition), 'rank1' (C2: the rank-1
    class alone must generate). Returns (rows, excluded, accept_rate)."""
    rows = []
    excluded = tried = accepted = 0
    for rec in recs:
        G = rec['G']
        places = sorted(rec['places'])
        sums = [0.0] * min(RANKS, len(places))
        got = local = 0
        while got < DRAWS and local < TRIES:
            local += 1
            tried += 1
            drawn = {p: rng.choice(G.keys) for (p, key) in places}
            if mode == 'subbound':
                if not EE.generates(G, EE.subbound_generators(rec, drawn)):
                    continue
            elif mode == 'rank1':
                if not EE.generates(G, [drawn[places[0][0]]]):
                    continue
            accepted += 1
            got += 1
            for i in range(len(sums)):
                if drawn[places[i][0]] not in G.squares:
                    sums[i] += 1.0
        if got == 0:
            excluded += 1
            continue
        rows.append(dict(h=G.h, d=rec['d'], ns=[s / got - 0.5 for s in sums],
                         got=got, k=subbound_partial_count(rec),
                         split_ns=split_nonsquare_below(rec)))
    rate = accepted / float(tried) if tried else 0.0
    return rows, excluded, rate


def profile(rows):
    """rank_table's numbers without its print."""
    out = {}
    for r in range(1, RANKS + 1):
        vals = [row['ns'][r - 1] for row in rows if len(row['ns']) >= r]
        if len(vals) >= 2:
            out[r] = mean_se(vals)
    for (a, b) in RANK_POOLS:
        vals = [sum(row['ns'][a - 1:b]) / (b - a + 1) for row in rows
                if len(row['ns']) >= b]
        if len(vals) >= 2:
            out[(a, b)] = mean_se(vals)
    return out


def diff(x, y):
    return x[0] - y[0], sqrt(x[1] ** 2 + y[1] ** 2)


def z_of(pair):
    return pair[0] / pair[1] if pair[1] else 0.0


def band_rank1(rows, lo, hi):
    vals = [row['ns'][0] + 0.5 for row in rows
            if lo < abs(row['d']) <= hi and row['ns']]
    if len(vals) < 2:
        return None
    return mean_se(vals) + (len(vals),)


