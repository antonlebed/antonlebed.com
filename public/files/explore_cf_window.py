from fractions import Fraction
from math import log, pi, sqrt


# ------------------------------------------------------------------ #
# CF machinery (exact, Fraction-based)                                #
# ------------------------------------------------------------------ #

def convergents(quots):
    """(p, q) numerator/denominator lists for a quotient prefix."""
    ps, qs = [], []
    pm2, qm2, pm1, qm1 = 0, 1, 1, 0
    for a in quots:
        p, q = a * pm1 + pm2, a * qm1 + qm2
        ps.append(p)
        qs.append(q)
        pm2, qm2, pm1, qm1 = pm1, qm1, p, q
    return ps, qs


def cylinder(quots, n):
    """The depth-n cell: interval of all reals whose CF starts with
    quots[:n+1] (entries a_0..a_n). Endpoints: convergent p_n/q_n and
    mediant (p_n + p_{n-1})/(q_n + q_{n-1}). Returns (lo, hi)."""
    ps, qs = convergents(quots[: n + 1])
    end1 = Fraction(ps[n], qs[n])
    if n == 0:
        end2 = Fraction(ps[0] + 1)
    else:
        end2 = Fraction(ps[n] + ps[n - 1], qs[n] + qs[n - 1])
    return (end1, end2) if end1 < end2 else (end2, end1)


def interval_cf(lo, hi, cap=10 ** 4):
    """Quotients shared by EVERY point of the open interval (lo, hi).
    Conservative at vertices: emits only what is forced."""
    out = []
    while len(out) < cap:
        alo, ahi = lo.numerator // lo.denominator, hi.numerator // hi.denominator
        if hi == ahi:            # hi is an integer: interior floors top out at ahi-1
            ahi -= 1
        if alo != ahi:
            break
        out.append(alo)
        flo, fhi = lo - alo, hi - alo
        if flo == 0:             # next reciprocal unbounded above: undetermined
            break
        lo, hi = 1 / fhi, 1 / flo
    return out


def mobius(mat, x):
    a, b, c, d = mat
    return (a * x + b) / (c * x + d)


def image_interval(mat, lo, hi):
    u, v = mobius(mat, lo), mobius(mat, hi)
    return (u, v) if u < v else (v, u)


def emitted(mat, quots, n):
    """Output quotients determined from the depth-n input cylinder."""
    lo, hi = cylinder(quots, n)
    return interval_cf(*image_interval(mat, lo, hi))


def q_rate(quots):
    """ln(q)/len for the deepest convergent of a quotient list."""
    ps, qs = convergents(quots)
    n = len(qs) - 1
    return log(qs[n]) / n if n >= 1 and qs[n] > 1 else 0.0


def lcg_quots(count, seed=12345):
    """Fixed pseudo-generic quotient string, values 1..5."""
    out, s = [], seed
    for _ in range(count):
        s = (1103515245 * s + 12345) % (2 ** 31)
        out.append(1 + (s >> 8) % 5)
    return out


def rational_cf(fr):
    """Canonical CF of a positive rational (last quotient > 1)."""
    out = []
    while True:
        a = fr.numerator // fr.denominator
        out.append(a)
        fr -= a
        if fr == 0:
            return out
        fr = 1 / fr


