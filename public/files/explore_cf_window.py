def mu(lo, hi):
    """Gauss measure of (lo, hi) inside (0,1)."""
    return (log(1 + hi) - log(1 + lo)) / log(2)


def e4():
    print("\nE4 THE OWN MEASURE")
    # (a) Gauss-Kuzmin masses sum to 1
    K = 10 ** 5
    s = sum(log(1 + 1 / (k * (k + 2))) for k in range(1, K)) / log(2)
    tail = 1 / (K * log(2))      # log(1+x) <= x, sum_{k>=K} 1/(k(k+2)) < 1/K
    print(f"    digit masses: partial sum {s:.8f} + tail < {tail:.1e}")
    check("Gauss-Kuzmin masses sum to 1 (within tail bound)",
          abs(s - 1) < tail)

    # (b) invariance on depth-1 cells: G^{-1}((1/(k+1), 1/k)) = U_j ...
    inv_ok = True
    for k in (1, 2, 5):
        cell = mu(Fraction(1, k + 1), Fraction(1, k))
        J = 10 ** 5
        pre = sum(mu(Fraction(k, j * k + 1), Fraction(k + 1, j * (k + 1) + 1))
                  for j in range(1, J))
        if abs(pre - cell) > 1e-4:
            inv_ok = False
        print(f"    invariance k={k}: mu(cell) {cell:.6f}  "
              f"mu(preimage) {pre:.6f}")
    check("Gauss measure invariant on depth-1 cells (1e-4 w/ cutoff)",
          inv_ok)

    # (c) grid mismatch on a depth-2 census
    lo_b, hi_b = 1 / (2 * log(2)), 1 / log(2)
    worst_lo, worst_hi = 1e9, 0
    for k1 in range(1, 21):
        for k2 in range(1, 21):
            a, b = cylinder([0, k1, k2], 2)
            r = mu(a, b) / float(b - a)
            worst_lo, worst_hi = min(worst_lo, r), max(worst_hi, r)
    deep_a, deep_b = cylinder([0, 40, 1], 2)
    deep = mu(deep_a, deep_b) / float(deep_b - deep_a)
    print(f"    mismatch mu(C)/|C| over depth-2 census: "
          f"[{worst_lo:.4f}, {worst_hi:.4f}] inside "
          f"[{lo_b:.4f}, {hi_b:.4f}]; near 0 (k1=40): {deep:.4f}")
    check("grid mismatch inside [1/(2ln2), 1/ln2]",
          lo_b - 1e-9 < worst_lo and worst_hi < hi_b + 1e-9)
    check("cells near 0 approach the top density 1/ln2", deep > 1.40)

    # (d) Rokhlin integral (Simpson quadrature)
    N = 100000
    h = 1.0 / N
    tot = 0.0
    for i in range(1, N):
        x = i * h
        w = 4 if i % 2 else 2
        tot += w * (2 * log(1 / x) / ((1 + x) * log(2)))
    # endpoint x=0 has an integrable log singularity; Simpson over
    # [h, 1] plus an exact-form patch on (0, h): int 2 ln(1/x) dx/(ln2 (1+x))
    # <= 2 h (1 - ln h)/ln 2  (crude but < 3e-4 at N = 1e5)
    rok = tot * h / 3
    target = pi ** 2 / (6 * log(2))
    print(f"    Rokhlin integral ~ {rok:.4f} vs entropy {target:.4f}")
    check("entropy = pi^2/(6 ln 2) within 2e-3", abs(rok - target) < 2e-3)

    # (e) mesh-rate fluctuation
    rates = {}
    for wname in ("phi", "lcg"):
        quots = WITNESSES[wname]
        lo, hi = cylinder(quots, 300)
        rates[wname] = log(1 / float(hi - lo)) / 300
    print(f"    mesh rate at phi {rates['phi']:.4f} (2 ln phi = "
          f"{2 * log((1 + sqrt(5)) / 2):.4f}); at lcg {rates['lcg']:.4f}; "
          f"entropy {target:.4f}; positional base-b: ln b, zero variance")
    check("phi mesh rate = 2 ln phi within 1e-3",
          abs(rates["phi"] - 2 * log((1 + sqrt(5)) / 2)) < 1e-3)
    check("mesh rate at lcg exceeds phi's floor",
          rates["lcg"] > rates["phi"] + 0.2)


