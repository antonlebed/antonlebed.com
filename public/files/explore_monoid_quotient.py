# ------------------------------------------------------------ the (m,t) model

def contributing_levels(b, am, ap):
    """The m with b^m <= n - 1, the criterion of the correction's F7."""
    n = len(sm.live_states(b, am, ap))
    out, m = [], 0
    while b ** m <= n - 1:
        out.append(m)
        m += 1
    return out


def word_range(b, am, ap, m):
    """[-T-, T+], the exact value range of a length-m word."""
    span = (b ** m - 1) // (b - 1)
    return -am * span, ap * span


def rank_of(b, am, ap, m, t):
    """How many live states survive v -> clamp(b^m v + t): the count of
    live v whose image is again live. Live = the integers in the crossed
    interval, which is what the clamp's interior is."""
    live = sm.live_states(b, am, ap)
    lo, hi = live[0], live[-1]
    return sum(1 for v in live if lo <= b ** m * v + t <= hi)


def model_elements(b, am, ap):
    """The rank-> = 2 elements of the quotient, as (m, t) pairs."""
    out = []
    for m in contributing_levels(b, am, ap):
        lo, hi = word_range(b, am, ap, m)
        for t in range(lo, hi + 1):
            if rank_of(b, am, ap, m, t) >= 2:
                out.append((m, t))
    return out


def model_product(b, am, ap, x, y, elements):
    """(*) with anything falling out of the element set sent to zero."""
    if x is None or y is None:
        return None
    m1, t1 = x
    m2, t2 = y
    z = (m1 + m2, b ** m2 * t1 + t2)
    return z if z in elements else None


def shifted(b, am, ap):
    """The element set in the coordinate u = t + am(b^m - 1)/(b - 1),
    where the product law loses every parameter but b."""
    out = set()
    for (m, t) in model_elements(b, am, ap):
        out.add((m, t + am * (b ** m - 1) // (b - 1)))
    return out


# ---------------------------------------------------------------- the algebra

def absorbing_blocks(blocks, delta):
    """C4: a state every digit fixes. Read off the TRANSITION function,
    never off the Moore output, which names the sign instead."""
    return {s for s in blocks if all(delta[s][d] == s for d in delta[s])}


def full_monoid(b, am, ap):
    """The syntactic monoid by closure, with the machine it lives on."""
    _, blocks, delta, _ = sm.quotient(b, am, ap)
    mon = sm.transition_monoid(blocks, delta)
    return blocks, delta, sorted(mon)


def map_rank(tup, blocks, absorbing):
    """How many states the map sends somewhere non-absorbing."""
    idx = {s: i for i, s in enumerate(blocks)}
    dead = {idx[s] for s in absorbing}
    return sum(1 for i in range(len(blocks)) if tup[i] not in dead)


def rees_quotient(mon, blocks, absorbing):
    """The rank-> = 2 elements; everything else is the quotient's zero."""
    return [t for t in mon if map_rank(t, blocks, absorbing) >= 2]


def compose(f, g):
    """Apply f, then g -- the order words are read in."""
    return tuple(g[f[i]] for i in range(len(f)))


def j_classes(elements, mult, zero=None):
    """Green's J-classes by mutual divisibility, over a finite semigroup
    given as an element list and a product. Two-sided ideals are computed
    by brute force, which is what a few hundred elements affords."""
    ideal = {}
    for x in elements:
        gen = {x}
        for a in elements + [None]:
            for c in elements + [None]:
                y = x
                if a is not None:
                    y = mult(a, y)
                if c is not None and y is not None:
                    y = mult(y, c)
                if y is not None:
                    gen.add(y)
        ideal[x] = frozenset(gen)
    classes, seen = [], set()
    for x in elements:
        if x in seen:
            continue
        cls = [y for y in elements
               if y not in seen
               and x in ideal[y] and y in ideal[x]]
        for y in cls:
            seen.add(y)
        classes.append(cls)
    return classes


def nilpotency_degree(elements, mult, generators):
    """The least k with every product of k elements zero, computed by
    powering the augmentation ideal from the LEVEL-1 elements alone.

    That is only sound if every non-identity element of Q is a product of
    surviving level-1 elements, which needs level 1 to be MERGED whenever
    a level above it exists -- otherwise a level-2 element could sit in Q
    with both of its factors outside. It always is: a level m >= 2 exists
    only when b^m <= n - 1, so n >= b^2 + 1 >= 2b + 1 > 2b, which is
    exactly level 1 merging. Checked over the sweep: 0 cells carry a split
    level 1 together with a level 2.
    """
    cur = set(generators)
    k = 1
    while cur:
        nxt = set()
        for x in cur:
            for g in generators:
                z = mult(x, g)
                if z is not None:
                    nxt.add(z)
        cur = nxt
        k += 1
        if k > 64:
            return None
    return k


# ------------------------------------------------------------------- controls

def control_c3(b, am, ap):
    """The (m, t) model against the closure quotient, as a bijective
    homomorphism element by element."""
    blocks, delta, mon = full_monoid(b, am, ap)
    absorbing = absorbing_blocks(blocks, delta)
    rees = rees_quotient(mon, blocks, absorbing)
    elements = model_elements(b, am, ap)
    eset = set(elements)

    def realize(x):
        m, t = x
        return sm.replay_map(blocks, delta, digits_for(b, am, ap, m, t))

    phi = {}
    for x in elements:
        phi[x] = realize(x)
    ok_bij = (len(set(phi.values())) == len(elements)
              and set(phi.values()) == set(rees))
    ok_hom = True
    for x in elements:
        for y in elements:
            z = model_product(b, am, ap, x, y, eset)
            got = compose(phi[x], phi[y])
            if z is None:
                if map_rank(got, blocks, absorbing) >= 2:
                    ok_hom = False
            elif phi[z] != got:
                ok_hom = False
    return len(absorbing), len(rees), ok_bij, ok_hom


def digits_for(b, am, ap, m, t):
    """Some length-m word over {-am..ap} of value t -- greedy from the
    top, which the contiguity of the digit set makes always possible."""
    out = []
    rem = t
    for i in range(m - 1, -1, -1):
        span = (b ** i - 1) // (b - 1)
        for d in range(-am, ap + 1):
            lo = d * b ** i - am * span
            hi = d * b ** i + ap * span
            if lo <= rem <= hi:
                out.append(d)
                rem -= d * b ** i
                break
        else:
            raise AssertionError(f"no digit at {(b, am, ap, m, t)}")
    assert rem == 0
    return tuple(out)


def control_c2(b, am, ap):
    """The J-class routine on the FULL monoid: it must find a class of
    size above 1, or J-triviality below means nothing."""
    blocks, delta, mon = full_monoid(b, am, ap)
    classes = j_classes(mon, lambda x, y: compose(x, y))
    return max(len(c) for c in classes)


