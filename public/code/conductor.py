def section_controls(recs):
    section("C  CONTROLS")
    d0s = [d for d in range(-200, -2) if d % 4 in (0, 1) and fundamental(d)]
    bad = [0, 0, 0, 0, 0]
    n = 0
    for d0 in d0s[::7]:
        for m in (2, 3, 4, 5, 6, 7, 9, 14, 18):
            R = Res(d0, m)
            us = R.units()
            bad[0] += len(us) != euler_order(d0, m)
            e = R.one()
            for x in us[:8]:
                for y in us[:8]:
                    bad[1] += R.conj(R.mul(x, y)) != \
                        R.mul(R.conj(x), R.conj(y))
                bad[1] += R.conj(R.conj(x)) != x
                bad[1] += R.mul(x, R.pow(x, len(us) - 1)) != e
            _, s3, r, rp, rm, ns = module_full(d0, m)
            bad[2] += ns != s3          # the image of x -> x^c, its size;
            #                             it tests something only at s3 > 1
            bad[3] += rp + rm != r
            n += 1
        for m in (14, 18, 36, 45, 63):
            _, _, _, rp, rm, _ = module_full(d0, m)
            bad[4] += (rp, rm) != module(d0, m)
    check("C1 the module engine: order, sigma, 3-Sylow, ranks, CRT",
          not any(bad), "%d cases; bad %s" % (n, bad))
    pins = [(d0, f, module(d0, f) + (usable_fixed(d0, f),), want)
            for d0, f, want in ((-19, 18, (1, 2, False)),
                                (-11, 18, (1, 2, True)))]
    bad_pin = [p for p in pins if p[2] != p[3]]
    check("C2 the pins at f = 18", not bad_pin,
          "; ".join("d0 = %d: %s" % (p[0], p[2]) for p in pins))
    per = {}
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        if f == 1 and -d0 <= HASSE_D:
            per[d0] = per.get(d0, 0) + 1
    off, nd = [], 0
    for d0 in range(-3, -HASSE_D - 1, -1):
        if d0 % 4 not in (0, 1) or not fundamental(d0):
            continue
        nd += 1
        want = (3 ** rank3_k(d0) - 1) // 2
        if per.get(d0, 0) != want:
            off.append((d0, per.get(d0, 0), want))
    check("C3 Hasse's count at every fundamental |d0| <= %d" % HASSE_D,
          not off, "%d discriminants, %d fields, off: %s"
          % (nd, sum(per.values()), off[:5]))
    return not any(bad) and not bad_pin and not off


def section_admissible(recs):
    section("A  THE ADMISSIBLE PRIMES")
    viol, occ = [], {}
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        for q, e in prime_powers(f):
            s = splitting(d0, q)
            occ[(q % 3 if q != 3 else 3, s)] = \
                occ.get((q % 3 if q != 3 else 3, s), 0) + 1
            if q != 3 and q % 3 == 1 and s != "split":
                viol.append((r["d"], q, s))
            if q != 3 and q % 3 == 2 and s != "inert":
                viol.append((r["d"], q, s))
            if q == 3 and (e > 2 or (e == 1 and d0 % 3 != 0)):
                viol.append((r["d"], q, e))
    for key in sorted(occ):
        print("  q %s  %-6s %5d occurrences"
              % ("= 3   " if key[0] == 3 else "= %d mod 3" % key[0],
                 key[1], occ[key]))
    check("A every conductor prime sits in k as (3) says", not viol,
          "%d fields, violations %s" % (len(recs), viol[:5]))


def section_ranks(recs):
    section("B  THE LOCAL RANKS AND THE USABLE LINE")
    off, use_off, unusable = [], [], []
    nf = 0
    t0 = time.time()
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        if f == 1:
            continue
        nf += 1
        pp = prime_powers(f)
        n1 = sum(1 for q, _ in pp if q != 3 and q % 3 == 1)
        other = sum(1 for q, _ in pp if q != 3)
        a = dict(pp).get(3, 0)
        ram3 = d0 % 3 == 0
        P = n1 + (a == 2)
        Mi = other + (a == 2) + (a == 1) + (a == 2 and ram3)
        got = module(d0, f)
        if got != (P, Mi):
            off.append((r["d"], d0, f, got, (P, Mi)))
        t = T.lines(d0, f)
        u = usable_fixed(d0, f)
        if u != (t >= 1):
            use_off.append((r["d"], d0, f, u, t))
        if got[0] > 0 and not u:
            unusable.append((r["d"], d0, f, splitting(d0, 3)))
    print("  %d fields with f > 1, %.1f s" % (nf, time.time() - t0))
    check("B1 plus rank P and minus rank as (4) says, at every field",
          not off, "off at %d: %s" % (len(off), off[:5]))
    check("B2 a usable fixed line exactly where t >= 1", not use_off,
          "off at %d: %s" % (len(use_off), use_off[:5]))
    pred = unusable
    shape = all(dict(prime_powers(f)).get(3, 0) == 2 and
                splitting(d0, 3) != "split" and
                not any(q % 3 == 1 for q, _ in prime_powers(f) if q != 3)
                for (_, d0, f, _) in unusable)
    n_pred = 0
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        if f % 9 == 0 and splitting(d0, 3) != "split" and \
                not any(q % 3 == 1 for q, _ in prime_powers(f) if q != 3):
            n_pred += 1
    print("  a fixed line exists unusable at %d fields (3 inert: %d, "
          "3 ramified: %d); the shape predicts %d"
          % (len(pred), sum(1 for x in pred if x[3] == "inert"),
             sum(1 for x in pred if x[3] == "ram"), n_pred))
    for x in pred[:12]:
        print("    d_K = %-7d d0 = %-6d f = %-4d 3 %s" % x)
    # B3 follows from B1 and B2, so it prints and is not checked
    print("  B3 (from B1, B2): the unusable fixed lines are the 9 | f, 3 not "
          "split cases: %s, %d printed, %d predicted"
          % (shape and len(pred) == n_pred, len(pred), n_pred))


def inverted_rank(d0, f):
    """rk Cl_f(k)_3^- is at least 2, by (8)."""
    r3 = rank3_k(d0)
    if f == 1:
        return r3 >= 2
    loc = module(d0, f)[1] - (1 if d0 == -3 else 0)
    return r3 >= 1 or loc >= 2


def section_sign(recs):
    section("S  THE SIGN OF THE SECOND LINE, AT 3-RANK 1")
    rows, thin = [], 0
    for r in recs:
        if r["r"] != 1:
            continue
        if len(r["triples"]) < T.MIN_SPLIT:
            thin += 1
            continue
        d0, f = T.fund_disc(r["d"])
        rows.append((r["d"], d0, f, r["t"], T.triple_index(r),
                     inverted_rank(d0, f),
                     any(m > 1 for _, _, m in fixed_minus_ranks(d0, f))))
    idx_off = [x for x in rows if x[4] != 3 ** x[3]]
    # triple.py's F2 at 3-rank 1, so a print
    print("  S1 (triple.py F2): the triple index is 3^t at %d of %d "
          "3-rank 1 fields; %d fields with fewer than %d mapped split "
          "primes left out" % (len(rows) - len(idx_off), len(rows), thin,
                               T.MIN_SPLIT))
    uni = [x for x in rows if x[3] == 0]
    deg = [x for x in rows if x[3] >= 1]
    miss = [x for x in uni if not x[5]]
    check("S2 every t = 0 field has an inverted second line (rank >= 2)",
          not miss, "%d uniform fields, without: %s"
          % (len(uni), [x[0] for x in miss][:8]))
    src = {"f = 1, rk_3 Cl(k) >= 2": 0, "f > 1, rk_3 Cl(k) >= 1": 0,
           "f > 1, local alone": 0}
    for x in uni:
        if x[2] == 1:
            src["f = 1, rk_3 Cl(k) >= 2"] += 1
        elif rank3_k(x[1]) >= 1:
            src["f > 1, rk_3 Cl(k) >= 1"] += 1
        else:
            src["f > 1, local alone"] += 1
    for k_, v in src.items():
        print("    uniform, %-26s %5d" % (k_, v))
    both = sum(1 for x in deg if x[5])
    print("  degenerate fields: %d, of which %d carry an inverted line "
          "too" % (len(deg), both))
    wild = [x[0] for x in rows if x[6]]
    print("  fields with a sigma-fixed local minus rank above 1 (the "
          "inverted line's usability not automatic): %d %s"
          % (len(wild), wild[:8]))
    return rows


def section_corner(recs):
    section("Z  CONDUCTOR 1")
    byh, miss, off3 = {}, [], {}
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        if f != 1:
            continue
        if r["h"] % 3 == 0:
            byh[r["h"]] = byh.get(r["h"], 0) + 1
            if rank3_k(d0) < 2:
                miss.append((r["d"], r["h"], rank3_k(d0)))
        else:
            k_ = rank3_k(d0)
            off3[k_] = off3.get(k_, 0) + 1
    print("  f = 1 and 3 | h, by h: %s" % sorted(byh.items()))
    print("  f = 1 and 3 !| h, by rk_3 Cl(k): %s" % sorted(off3.items()))
    # Z follows from Z2 (3 | h is rk_3 Cl(K) >= 1), so a print
    print("  Z (from Z2): f = 1 fields with 3 | h and rk_3 Cl(k) < 2: %d of "
          "%d %s" % (len(miss), sum(byh.values()), miss[:8]))
    joint, off = {}, []
    for r in recs:
        d0, f = T.fund_disc(r["d"])
        if f != 1:
            continue
        rK = sum(1 for n in r["inv"] if n % 3 == 0)
        rk = rank3_k(d0)
        joint[(rK, rk)] = joint.get((rK, rk), 0) + 1
        if rK != rk - 1:
            off.append((r["d"], tuple(r["inv"]), rk))
    print("  f = 1, (rk_3 Cl(K), rk_3 Cl(k)): %s" % sorted(joint.items()))
    check("Z2 rk_3 Cl(K) = rk_3 Cl(k) - 1 at every f = 1 field (Gerth)",
          not off, "%d fields, off: %s" % (sum(joint.values()), off[:8]))


def section_h3(recs):
    section("H  THE h = 3 POPULATION TO %d" % H3_CAP)
    h3 = [r for r in recs if r["h"] == 3 and -r["d"] <= H3_CAP]
    rd = [r for r in h3 if len(r["triples"]) >= T.MIN_SPLIT]
    print("  %d fields at h = 3, %d with %d or more mapped split primes, "
          "%d at t >= 1, %d at f = 1"
          % (len(h3), len(rd), T.MIN_SPLIT,
             sum(1 for r in rd if r["t"] >= 1),
             sum(1 for r in rd if T.fund_disc(r["d"])[1] == 1)))


