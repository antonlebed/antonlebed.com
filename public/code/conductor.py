_R3 = {}


def rank3_k(d0):
    """rk_3 Cl(k), off principal.py's form class group."""
    if d0 not in _R3:
        G = PR.Group(d0)
        k = sum(1 for i in range(G.h) if G.power(i, 3) == G.e)
        r = 0
        while 3 ** r < k:
            r += 1
        assert 3 ** r == k
        _R3[d0] = r
    return _R3[d0]


def fundamental(d0):
    return T.fund_disc(d0) == (d0, 1)


