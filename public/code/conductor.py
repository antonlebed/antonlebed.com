# the ring O_k / m and its unit group as a module under conjugation

class Res:
    """O_k / m for k = Q(sqrt d0), elements a + b w with w^2 = t w + n:
    w = (1 + sqrt d0)/2 when d0 = 1 mod 4, else sqrt(d0/4)."""

    def __init__(self, d0, m):
        self.d0, self.m = d0, m
        if d0 % 4 == 1:
            self.t, self.n = 1, (d0 - 1) // 4
        else:
            self.t, self.n = 0, d0 // 4

    def mul(self, x, y):
        (a, b), (c, d) = x, y
        m = self.m
        return ((a * c + b * d * self.n) % m,
                (a * d + b * c + b * d * self.t) % m)

    def conj(self, x):
        """sigma(a + b w) = a + b (t - w), since w + sigma(w) = t."""
        a, b = x
        return ((a + b * self.t) % self.m, (-b) % self.m)

    def norm(self, x):
        a, b = x
        return a * a + a * b * self.t - b * b * self.n

    def one(self):
        return (1 % self.m, 0)

    def units(self):
        m = self.m
        return [(a, b) for a in range(m) for b in range(m)
                if gcd(self.norm((a, b)) % m, m) == 1]

    def pow(self, x, e):
        r, base = self.one(), x
        while e:
            if e & 1:
                r = self.mul(r, base)
            base = self.mul(base, base)
            e >>= 1
        return r


def splitting(d0, q):
    if d0 % q == 0:
        return "ram"
    if q == 2:
        return "split" if d0 % 8 == 1 else "inert"
    return "split" if pow(d0 % q, (q - 1) // 2, q) == 1 else "inert"


def prime_powers(n):
    out, d = [], 2
    while d * d <= n:
        e = 0
        while n % d == 0:
            n //= d
            e += 1
        if e:
            out.append((d, e))
        d += 1
    if n > 1:
        out.append((n, 1))
    return out


def euler_order(d0, m):
    num, den = m * m, 1
    for q, _ in prime_powers(m):
        s = splitting(d0, q)
        if s == "split":
            num, den = num * (q - 1) ** 2, den * q * q
        elif s == "inert":
            num, den = num * (q * q - 1), den * q * q
        else:
            num, den = num * (q - 1), den * q
    assert num % den == 0
    return num // den


def rank3(R, elems):
    """The F_3-rank of a 3-group given as its list of elements."""
    e = R.one()
    k = sum(1 for x in elems if R.pow(x, 3) == e)
    r = 0
    while 3 ** r < k:
        r += 1
    assert 3 ** r == k
    return r


def module_full(d0, m):
    """(|units|, |3-part|, rank, plus rank, minus rank) of the 3-part of
    (O_k/m)^* under sigma, by brute force."""
    R = Res(d0, m)
    us = R.units()
    n = len(us)
    s3, c = 1, n
    while c % 3 == 0:
        c //= 3
        s3 *= 3
    if s3 == 1:
        return n, 1, 0, 0, 0, 1
    syl = sorted({R.pow(x, c) for x in us})
    u = (s3 + 1) // 2                      # 2u = 1 mod s3
    plus, minus = set(), set()
    for x in syl:
        sx = R.conj(x)
        plus.add(R.pow(R.mul(x, sx), u))
        minus.add(R.pow(R.mul(x, R.pow(sx, s3 - 1)), u))
    return (n, s3, rank3(R, syl), rank3(R, sorted(plus)),
            rank3(R, sorted(minus)), len(syl))


_MOD = {}


def module(d0, m):
    """(plus rank, minus rank) over m, summed over its prime powers (the
    CRT step C1 controls), each brute-forced once."""
    rp = rm = 0
    for q, e in prime_powers(m):
        key = (d0, q ** e)
        if key not in _MOD:
            _MOD[key] = module_full(d0, q ** e)
        rp += _MOD[key][3]
        rm += _MOD[key][4]
    return rp, rm


def usable_fixed(d0, f):
    """(5): a prime of k over a split q | f with nontrivial local
    3-part."""
    for q, e in prime_powers(f):
        if splitting(d0, q) == "split":
            key = (d0, q ** e)
            if key not in _MOD:
                _MOD[key] = module_full(d0, q ** e)
            if _MOD[key][1] > 1:
                return True
    return False


def fixed_minus_ranks(d0, f):
    """[(q, e, minus rank)] at the prime powers of f whose prime sigma
    fixes (inert or ramified in k)."""
    out = []
    for q, e in prime_powers(f):
        if splitting(d0, q) != "split":
            module(d0, q ** e)
            out.append((q, e, _MOD[(d0, q ** e)][4]))
    return out


